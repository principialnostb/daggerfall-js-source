// THE JOURNAL'S LETTERING, baked from Jacquard 12 (app/launcher/fonts/Jacquard12-latin.woff2, SIL Open Font License 1.1,
// app/launcher/fonts/OFL-Jacquard12.txt) into server-account/src/journalFont.js: each glyph's shape at MASTER_PX, its
// offsets and its advance, so the account service can letter its worn-paper pictures without a font engine.
//
//     node tools/journalFontBake.mjs                 (CHROMIUM=<path> to use another browser build)
//
// The glyphs are drawn by the preinstalled Chromium (Playwright), each alone on a canvas, read back as coverage, cropped
// to their ink, and packed one after another; the pack is deflated and written as base64 beside a table of metrics.
// A character the font does not hold is left out, and the service draws nothing for it.
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { isMain } from './lib/isMain.mjs';

/** The size the shapes are kept at, in pixels: drawn smaller, they are sampled down. */
export const MASTER_PX = 48;
/** The characters baked: printable ASCII, then the Latin-1 letters and the typographic marks the journal writes. */
export const BAKED_CHARS = [
  ...Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)),
  ...'ÀÁÂÄÇÈÉÊËÍÎÏÑÓÔÖÙÚÛÜàáâäçèéêëíîïñóôöùúûüß',
  ...'’‘“”–—·•×…',
].join('');

const FONT = new URL('../app/launcher/fonts/Jacquard12-latin.woff2', import.meta.url);
const OUT = new URL('../server-account/src/journalFont.js', import.meta.url);

export async function bake() {
  const { chromium } = createRequire(import.meta.url)('playwright');
  const b64 = readFileSync(FONT).toString('base64');
  // the project's Playwright may pin another build than the machine holds: CHROMIUM names one to use instead
  const browser = await chromium.launch(process.env.CHROMIUM ? { executablePath: process.env.CHROMIUM } : {});
  try {
    const page = await browser.newPage();
    await page.setContent(`<style>@font-face{font-family:J;src:url(data:font/woff2;base64,${b64})}</style><canvas id=c></canvas>`);
    await page.evaluate(() => document.fonts.load('48px J'));
    return await page.evaluate(
      ({ chars, px }) => {
        const c = /** @type {HTMLCanvasElement} */ (document.getElementById('c'));
        const W = px * 3, H = px * 2, base = Math.round(px * 1.4);
        c.width = W;
        c.height = H;
        const x = /** @type {CanvasRenderingContext2D} */ (c.getContext('2d', { willReadFrequently: true }));
        const probe = (/** @type {string} */ ch, /** @type {string} */ fam) => {
          x.font = `${px}px ${fam}`;
          return x.measureText(ch).width;
        };
        const glyphs = [];
        const bytes = [];
        x.font = `${px}px J`;
        const m = x.measureText('Hg');
        for (const ch of chars) {
          // A glyph the font lacks falls back to another face; the two fallbacks then measure alike.
          if (ch !== ' ' && probe(ch, 'J, monospace') !== probe(ch, 'J, serif')) continue;
          x.clearRect(0, 0, W, H);
          x.fillStyle = '#000';
          x.font = `${px}px J`;
          x.textBaseline = 'alphabetic';
          const ox = px;
          x.fillText(ch, ox, base);
          const adv = x.measureText(ch).width;
          const d = x.getImageData(0, 0, W, H).data;
          let x0 = W, y0 = H, x1 = -1, y1 = -1;
          for (let yy = 0; yy < H; yy++)
            for (let xx = 0; xx < W; xx++)
              if (d[(yy * W + xx) * 4 + 3] > 8) {
                if (xx < x0) x0 = xx;
                if (xx > x1) x1 = xx;
                if (yy < y0) y0 = yy;
                if (yy > y1) y1 = yy;
              }
          const w = x1 >= x0 ? x1 - x0 + 1 : 0, h = y1 >= y0 ? y1 - y0 + 1 : 0;
          glyphs.push([ch.codePointAt(0), bytes.length, w, h, w ? x0 - ox : 0, h ? y0 - base : 0, Math.round(adv * 100) / 100]);
          for (let yy = 0; yy < h; yy++) for (let xx = 0; xx < w; xx++) bytes.push(d[((y0 + yy) * W + x0 + xx) * 4 + 3]);
        }
        return { glyphs, bytes, ascent: Math.round(m.fontBoundingBoxAscent), descent: Math.round(m.fontBoundingBoxDescent) };
      },
      { chars: BAKED_CHARS, px: MASTER_PX },
    );
  } finally {
    await browser.close();
  }
}

async function main() {
  const { glyphs, bytes, ascent, descent } = await bake();
  const packed = deflateSync(Uint8Array.from(bytes), { level: 9 }).toString('base64');
  const lines = [
    '// @ts-check',
    '// GENERATED by tools/journalFontBake.mjs from Jacquard 12 (app/launcher/fonts/Jacquard12-latin.woff2) - do not edit;',
    '// re-run the bake. Jacquard 12 is Copyright 2023 The Soft Type Project Authors, under the SIL Open Font License 1.1',
    '// (app/launcher/fonts/OFL-Jacquard12.txt). Each glyph: [code point, offset into the pack, width, height, left from',
    '// the pen, top from the baseline, advance], at `px`; the pack is the glyphs\' coverage, deflated, base64.',
    `export const JOURNAL_FONT = Object.freeze({`,
    `  px: ${MASTER_PX},`,
    `  ascent: ${ascent},`,
    `  descent: ${descent},`,
    `  glyphs: ${JSON.stringify(glyphs)},`,
    `  pack: '${packed}',`,
    `});`,
    '',
  ];
  writeFileSync(OUT, lines.join('\n'));
  console.log(`${glyphs.length} glyphs, ${bytes.length} bytes of coverage, ${packed.length} base64 characters`);
}

if (isMain(import.meta.url)) await main();
